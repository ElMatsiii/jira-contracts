/**
 * challenger-verify-reply-schema.js
 * Adversarial validation of analytics.reply schema compliance using Ajv
 */

const fs = require('fs');
const path = require('path');
const Ajv = require('ajv');
const addFormats = require('ajv-formats');

const schemaPath = path.resolve(__dirname, '../schemas/analytics.reply.json');
const schemaContent = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));

const ajv = new Ajv({ allErrors: true, strict: false, strictNumbers: true, validateFormats: true });
addFormats(ajv);

const validate = ajv.compile(schemaContent);

let totalTests = 0;
let passedTests = 0;
let failedTests = 0;

function assertValid(name, payload) {
  totalTests++;
  const valid = validate(payload);
  if (valid) {
    console.log(`[PASS] ${name}`);
    passedTests++;
  } else {
    console.error(`[FAIL] ${name}: Expected valid, but got errors:`, validate.errors);
    failedTests++;
  }
}

function assertInvalid(name, payload, expectedKeyword) {
  totalTests++;
  const valid = validate(payload);
  if (!valid) {
    const hasKeyword = !expectedKeyword || validate.errors.some(e => e.keyword === expectedKeyword);
    if (hasKeyword) {
      console.log(`[PASS] ${name} (Properly rejected with keyword: ${expectedKeyword || 'any'})`);
      passedTests++;
    } else {
      console.error(`[FAIL] ${name}: Rejected, but expected error keyword '${expectedKeyword}'. Got:`, validate.errors);
      failedTests++;
    }
  } else {
    console.error(`[FAIL] ${name}: Expected payload to be rejected, but it PASSED!`);
    failedTests++;
  }
}

console.log('============================================================');
console.log('   CHALLENGER ADVERSARIAL SCHEMA CONFORMANCE VERIFICATION   ');
console.log('   Target Schema: schemas/analytics.reply.json               ');
console.log('============================================================\n');

